void UK2Node_SpawnSyncActor::ExpandNode(FKismetCompilerContext& Compiler, UEdGraph* SourceGraph)
{
	using namespace HUICRSpawnNode;
	const auto* Schema = Compiler.GetSchema();
	TSet<FName> SuppliedMembers;
	UK2Node_MakeStruct* DefaultPins = nullptr;
	// Expanding even an untouched split pin gives its parent a synthetic Make Struct link.
	for (const UEdGraphPin* Pin : Pins)
	{
		if (Pin->bOrphanedPin || Pin->ParentPin || !Pin->PinName.ToString().StartsWith(TEXT("Member."))) { continue; }
		if (HasSuppliedValue(Pin))
		{
			SuppliedMembers.Add(Pin->PinName);
		}
		else if (!Pin->SubPins.IsEmpty() && CachedSchema)
		{
			if (!DefaultPins)
			{
				DefaultPins = NewObject<UK2Node_MakeStruct>(SourceGraph, NAME_None, RF_Transient);
				DefaultPins->StructType = CachedSchema;
				DefaultPins->AllocateDefaultPins();
			}
			FString PropertyName = Pin->PinName.ToString();
			PropertyName.RemoveFromStart(TEXT("Member."));
			UEdGraphPin* Default = DefaultPins->FindPin(FName(*PropertyName), EGPD_Input);
			if (!Default || HasSplitOverride(*Pin, *Default, *Schema)) { SuppliedMembers.Add(Pin->PinName); }
		}
	}
	const UEdGraphPin* Force = FindPin(StructDefaults);
	const bool bSendFields = !SuppliedMembers.IsEmpty() || (Force && Force->DefaultValue.ToBool());
	Super::ExpandNode(Compiler, SourceGraph);
	UEdGraphPin* ClassPin = FindPinChecked(Class);
	if (ClassPin->LinkedTo.IsEmpty() && !ClassPin->DefaultObject)
	{
		Compiler.MessageLog.Error(TEXT("@@ requires a Sync Actor class."), this);
		BreakAllNodeLinks();
		return;
	}
	if (bSendFields && !HUICRSyncFields::CanUseLegacyBytes(CachedSchema))
	{
		Compiler.MessageLog.Error(TEXT("@@ requires a value-only Shared Payload Struct to send initial values. Check the selected class and refresh this node."), this);
		BreakAllNodeLinks();
		return;
	}
	auto SpawnCall = [&](UClass* Owner, FName Name)
	{
		auto* Call = Compiler.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
		Call->SetFromFunction(Owner->FindFunctionByName(Name));
		Call->AllocateDefaultPins();
		return Call;
	};
	auto* Call = SpawnCall(UHUICRSyncPayloadLibrary::StaticClass(), GET_FUNCTION_NAME_CHECKED(UHUICRSyncPayloadLibrary, SpawnSyncActorWithInitialValues));
	for (FName PinName : { Class, Transform, Target, LocalSpace, World, Schema->PN_Then, Schema->PN_ReturnValue })
	{
		if (UEdGraphPin* Pin = FindPin(PinName))
		{
			Compiler.MovePinLinksToIntermediate(*Pin, *Call->FindPinChecked(PinName));
		}
	}
	if (bSendFields)
	{
		auto* Make = Compiler.SpawnIntermediateNode<UK2Node_MakeStruct>(this, SourceGraph);
		Make->StructType = CachedSchema;
		Make->bMadeAfterOverridePinRemoval = true;
		Make->AllocateDefaultPins();
		for (TFieldIterator<FProperty> It(CachedSchema); It; ++It)
		{
			auto* Member = Make->FindPin(It->GetFName(), EGPD_Input);
			const FName MemberName = UK2Node_HUICRSyncPayload::MemberPinName(It->GetFName());
			if (!SuppliedMembers.Contains(MemberName))
			{
				// MakeStruct skips unconnected pins with ignored defaults. The UDS constructor
				// supplies authored values, including non-empty arrays, maps and nested structs.
				if (Member) { Member->bDefaultValueIsIgnored = true; }
				continue;
			}
			auto* Input = FindPin(MemberName);
			if (!Input || !Member || Input->PinType != Member->PinType)
			{
				Compiler.MessageLog.Error(*FString::Printf(TEXT("@@ cannot pass the initial field '%s'. Refresh the node and check its field type."), *It->GetAuthoredName()), this);
				continue;
			}
			Compiler.MovePinLinksToIntermediate(*Input, *Member);
		}
		auto* Box = SpawnCall(UBlueprintInstancedStructLibrary::StaticClass(), GET_FUNCTION_NAME_CHECKED(UBlueprintInstancedStructLibrary, MakeInstancedStruct));
		auto* Value = Box->FindPinChecked(TEXT("Value"));
		Value->PinType.PinCategory = Schema->PC_Struct;
		Value->PinType.PinSubCategoryObject = CachedSchema;
		Compiler.MovePinLinksToIntermediate(*GetExecPin(), *Box->GetExecPin());
		if (!Schema->TryCreateConnection(Make->FindPin(CachedSchema->GetFName(), EGPD_Output), Value) ||
			!Schema->TryCreateConnection(Box->GetReturnValuePin(), Call->FindPinChecked(Initial)) ||
			!Schema->TryCreateConnection(Box->FindPinChecked(Schema->PN_Then), Call->GetExecPin()))
		{
			Compiler.MessageLog.Error(TEXT("@@ could not construct the initial payload for the selected class."), this);
		}
	}
	else
	{
		Compiler.MovePinLinksToIntermediate(*GetExecPin(), *Call->GetExecPin());
		if (UEdGraphPin* DynamicValues = FindPin(Initial))
		{
			Compiler.MovePinLinksToIntermediate(*DynamicValues, *Call->FindPinChecked(Initial));
		}
	}
	BreakAllNodeLinks();
}

