namespace HUICRSpawnNode
{
	const FName Class(TEXT("SpawnClass"));
	const FName Transform(TEXT("SpawnTransform"));
	const FName Target(TEXT("Target"));
	const FName World(TEXT("WorldContextObject"));
	const FName LocalSpace(TEXT("bUseLocalSpace"));
	const FName StructDefaults(TEXT("bUseStructDefaults"));
	const FName Initial(TEXT("InitialValues"));
	const FName SchemaDependency(TEXT("SharedPayloadSchema"));

	UClass* ResolveClass(const UEdGraphPin* Pin)
	{
		if (!Pin) { return nullptr; }
		return Pin->LinkedTo.IsEmpty() ? Cast<UClass>(Pin->DefaultObject) :
			Cast<UClass>(Pin->LinkedTo[0]->PinType.PinSubCategoryObject.Get());
	}

	bool IsInitialPin(const UEdGraphPin* Pin)
	{
		while (Pin->ParentPin) { Pin = Pin->ParentPin; }
		return Pin->PinName == Initial || Pin->PinName == StructDefaults || Pin->PinName == SchemaDependency ||
			Pin->PinName.ToString().StartsWith(TEXT("Member."));
	}

	bool HasSuppliedValue(const UEdGraphPin* Pin)
	{
		return !Pin->LinkedTo.IsEmpty() || (!Pin->bDefaultValueIsIgnored && !Pin->DoesDefaultValueMatchAutogenerated());
	}

	// Splitting a nonzero vector copies its components into the child pins' *values*, while
	// their autogenerated defaults stay zero. Compare against UE's split of the same default.
	bool HasSplitOverride(const UEdGraphPin& Input, UEdGraphPin& DefaultPin, const UEdGraphSchema_K2& Schema)
	{
		if (!Input.LinkedTo.IsEmpty() || !Schema.DoesDefaultValueMatch(Input, DefaultPin.GetDefaultAsString())) { return true; }
		if (Input.SubPins.IsEmpty()) { return false; }
		Schema.SplitPin(&DefaultPin, false);
		if (Input.SubPins.Num() != DefaultPin.SubPins.Num()) { return true; }
		for (int32 Index = 0; Index < Input.SubPins.Num(); ++Index)
		{
			if (HasSplitOverride(*Input.SubPins[Index], *DefaultPin.SubPins[Index], Schema)) { return true; }
		}
		return false;
	}
}

UClass* UK2Node_SpawnSyncActor::GetSpawnClass() const
{
	return HUICRSpawnNode::ResolveClass(FindPin(HUICRSpawnNode::Class));
}

void UK2Node_SpawnSyncActor::AllocateDefaultPins()
{
	using namespace HUICRSpawnNode;
	Super::AllocateDefaultPins();
	const auto* Schema = GetDefault<UEdGraphSchema_K2>();
	CreatePin(EGPD_Input, Schema->PC_Exec, Schema->PN_Execute);
	CreatePin(EGPD_Output, Schema->PC_Exec, Schema->PN_Then);
	CreatePin(EGPD_Input, Schema->PC_Class, AHUICRSyncActor::StaticClass(), Class);
	UEdGraphPin* Pose = CreatePin(EGPD_Input, Schema->PC_Struct, TBaseStructure<FTransform>::Get(), Transform);
	Schema->SetPinAutogeneratedDefaultValueBasedOnType(Pose);
	Pose->PinToolTip = TEXT("The spawn transform in PC space. Enable Use Local Space for a transform in the calling headset's world.");
	UEdGraphPin* Local = CreatePin(EGPD_Input, Schema->PC_Boolean, LocalSpace);
	Schema->SetPinAutogeneratedDefaultValueBasedOnType(Local);
	Local->bAdvancedView = true;
	UEdGraphPin* TargetPin = CreatePin(EGPD_Input, Schema->PC_Object, UObject::StaticClass(), Target);
	TargetPin->PinToolTip = TEXT("Connect a sync manager, subsystem or world object to choose its session. Leave empty to use the caller's session.");
	TargetPin->bAdvancedView = true;
	const UBlueprint* BP = FBlueprintEditorUtils::FindBlueprintForNode(this);
	if (BP && (BP->BlueprintType == BPTYPE_FunctionLibrary ||
		(BP->ParentClass && BP->ParentClass->HasMetaDataHierarchical(FBlueprintMetadata::MD_ShowWorldContextPin))))
	{
		CreatePin(EGPD_Input, Schema->PC_Object, UObject::StaticClass(), World);
	}
	CreatePin(EGPD_Output, Schema->PC_Boolean, Schema->PN_ReturnValue)->PinToolTip =
		TEXT("True if this PC spawned the actor or this headset sent its spawn request.");
	if (AdvancedPinDisplay == ENodeAdvancedPins::NoPins) { AdvancedPinDisplay = ENodeAdvancedPins::Hidden; }
}

void UK2Node_SpawnSyncActor::AddInitialPins(const UEdGraphPin* ClassPin)
{
	using namespace HUICRSpawnNode;
	const auto* Schema = GetDefault<UEdGraphSchema_K2>();
	UClass* Selected = ResolveClass(ClassPin);
	const auto* Actor = Selected && Selected->IsChildOf(AHUICRSyncActor::StaticClass()) ? Selected->GetDefaultObject<AHUICRSyncActor>() : nullptr;
	const UBlueprint* SelectedBP = Selected ? Cast<UBlueprint>(Selected->ClassGeneratedBy) : nullptr;
	if (!SelectedBP || !SelectedBP->bBeingCompiled || !CachedSchema)
	{
		CachedSchema = Actor ? Actor->SharedPayloadStruct.Get() : nullptr;
	}
	if (!CachedSchema)
	{
		if (ClassPin && !ClassPin->LinkedTo.IsEmpty())
		{
			UEdGraphPin* Values = CreatePin(EGPD_Input, Schema->PC_Struct, FInstancedStruct::StaticStruct(), Initial);
			Values->bAdvancedView = true;
			Values->PinToolTip = TEXT("Optional initial values for a class selected at runtime. The struct must match that class's Shared Payload Struct.");
			Schema->SetPinAutogeneratedDefaultValueBasedOnType(Values);
		}
		return;
	}
	PreloadObject(CachedSchema);
	// UE finds dependent graphs during a user-defined struct edit by inspecting node pin types.
	UEdGraphPin* Dependency = CreatePin(EGPD_Input, Schema->PC_Struct, CachedSchema.Get(), SchemaDependency);
	Dependency->bHidden = true;
	Dependency->bNotConnectable = true;
	Dependency->bDefaultValueIsIgnored = true;
	UEdGraphPin* Force = CreatePin(EGPD_Input, Schema->PC_Boolean, StructDefaults);
	Force->bAdvancedView = true;
	Force->bNotConnectable = true;
	Force->PinFriendlyName = LOCTEXT("SendStructDefaults", "Send Struct Defaults");
	Force->PinToolTip = TEXT("Send initial values even when every field equals its struct default. Leave off to let the actor initialize itself when no field is edited or connected.");
	Schema->SetPinAutogeneratedDefaultValueBasedOnType(Force);
	FStructOnScope Defaults(CachedSchema);
	for (TFieldIterator<FProperty> It(CachedSchema); It; ++It)
	{
		FEdGraphPinType PinType;
		if (!HUICRSyncFields::IsSupportedField(**It) || !Schema->ConvertPropertyToPinType(*It, PinType)) { continue; }
		UEdGraphPin* Field = CreatePin(EGPD_Input, PinType, UK2Node_HUICRSyncPayload::MemberPinName(It->GetFName()));
		Field->PinFriendlyName = It->GetDisplayNameText();
		Field->PinToolTip = It->GetToolTipText().ToString();
		Field->bDefaultValueIsIgnored = PinType.IsContainer();
		FString DefaultText;
		if (!PinType.IsContainer() && FBlueprintEditorUtils::PropertyValueToString(*It, Defaults.GetStructMemory(), DefaultText) &&
			Schema->IsPinDefaultValid(Field, DefaultText, nullptr, FText::GetEmpty()).IsEmpty())
		{
			Schema->SetPinAutogeneratedDefaultValue(Field, DefaultText);
		}
		else
		{
			Schema->SetPinAutogeneratedDefaultValueBasedOnType(Field);
		}
	}
}

void UK2Node_SpawnSyncActor::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	AllocateDefaultPins();
	UEdGraphPin** OldClass = OldPins.FindByPredicate([](const UEdGraphPin* Pin) { return Pin && Pin->PinName == HUICRSpawnNode::Class; });
	AddInitialPins(OldClass ? *OldClass : nullptr);
	RestoreSplitPins(OldPins);
}

void UK2Node_SpawnSyncActor::RefreshClassPins()
{
	// Keep the class pin alive while the graph schema is notifying both ends of a connection.
	TArray<UEdGraphPin*> OldInputs = Pins.FilterByPredicate(HUICRSpawnNode::IsInitialPin);
	for (UEdGraphPin* Pin : OldInputs) { Pins.RemoveSingle(Pin); }
	AddInitialPins(FindPin(HUICRSpawnNode::Class));
	RestoreSplitPins(OldInputs);
	RewireOldPinsToNewPins(OldInputs, Pins, nullptr);
	DestroyPinList(OldInputs);
	GetGraph()->NotifyGraphChanged();
}

void UK2Node_SpawnSyncActor::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);
	if (Pin && Pin->PinName == HUICRSpawnNode::Class) { RefreshClassPins(); }
}

void UK2Node_SpawnSyncActor::PinConnectionListChanged(UEdGraphPin* Pin)
{
	Super::PinConnectionListChanged(Pin);
	if (Pin && Pin->PinName == HUICRSpawnNode::Class) { RefreshClassPins(); }
}

bool UK2Node_SpawnSyncActor::HasExternalDependencies(TArray<UStruct*>* OptionalOutput) const
{
	bool bHasDependencies = Super::HasExternalDependencies(OptionalOutput);
	const UBlueprint* Owner = FBlueprintEditorUtils::FindBlueprintForNode(this);
	for (UStruct* Dependency : { static_cast<UStruct*>(GetSpawnClass()), static_cast<UStruct*>(CachedSchema.Get()) })
	{
		if (Dependency && !Dependency->IsNative() && (!Owner || Dependency != Owner->GeneratedClass.Get()))
		{
			bHasDependencies = true;
			if (OptionalOutput) { OptionalOutput->AddUnique(Dependency); }
		}
	}
	return bHasDependencies;
}

void UK2Node_SpawnSyncActor::GetMenuActions(FBlueprintActionDatabaseRegistrar& Registrar) const
{
	if (Registrar.IsOpenForRegistration(GetClass()))
	{
		Registrar.AddBlueprintAction(GetClass(), UBlueprintNodeSpawner::Create(GetClass()));
	}
}

