void UK2Node_HUICRSyncPayload::ExpandNode(FKismetCompilerContext& Compiler, UEdGraph* SourceGraph)
{
	Super::ExpandNode(Compiler, SourceGraph);
	UScriptStruct* Struct = ResolvePayloadStruct();
	if (!Struct)
	{
		Compiler.MessageLog.Error(TEXT("@@ requires a Shared Payload Struct in Class Defaults."), this);
		BreakAllNodeLinks();
		return;
	}
	if (UsesInitialPayload() && !HUICRSyncFields::CanUseLegacyBytes(Struct))
	{
		Compiler.MessageLog.Error(TEXT("@@ requires a value-only Shared Payload Struct for spawn data. Use a shared ID for an object reference and remove delegates from this struct."), this);
		BreakAllNodeLinks();
		return;
	}
	const UEdGraphSchema_K2* Schema = Compiler.GetSchema();
	const bool bRead = IsReadNode();
	const bool bSetSource = IsA<UK2Node_SetSyncFieldSource>();
	FProperty* SelectedProperty = bSetSource ? HUICRSyncNode::FindSelectedProperty(Struct, SelectedField) : nullptr;
	if (bSetSource && !SelectedProperty)
	{
		Compiler.MessageLog.Error(TEXT("@@ selects a field missing from the Shared Payload Struct. Pick a field from the dropdown."), this);
		BreakAllNodeLinks();
		return;
	}

	auto SpawnCall = [&](UClass* Owner, FName FunctionName)
	{
		auto* Call = Compiler.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
		Call->SetFromFunction(Owner->FindFunctionByName(FunctionName));
		Call->AllocateDefaultPins();
		return Call;
	};
	auto Connect = [&](UEdGraphPin* First, UEdGraphPin* Second)
	{
		if (!First || !Second || !Schema->TryCreateConnection(First, Second))
		{
			Compiler.MessageLog.Error(TEXT("@@ could not connect its internal payload pins. Refresh the node and check the shared structure."), this);
		}
	};
	auto MoveMember = [&](const FProperty& Property, UK2Node* StructNode)
	{
		UEdGraphPin* Pin = FindPin(bSetSource ? HUICRSyncNode::Value : MemberPinName(Property.GetFName()));
		UEdGraphPin* Intermediate = StructNode->FindPin(Property.GetFName(), bRead ? EGPD_Output : EGPD_Input);
		if (!Pin || !Intermediate || Pin->PinType != Intermediate->PinType)
		{
			Compiler.MessageLog.Error(*FString::Printf(TEXT("@@ cannot expose '%s'. Check the field type and refresh the node."), *Property.GetAuthoredName()), this);
			return;
		}
		Compiler.MovePinLinksToIntermediate(*Pin, *Intermediate);
	};
	FName FunctionName = GET_FUNCTION_NAME_CHECKED(AHUICRSyncActor, PrepareOutgoingPayloadInternal);
	if (bRead)
	{
		FunctionName = UsesInitialPayload()
			? GET_FUNCTION_NAME_CHECKED(AHUICRSyncActor, ReadInitialPayloadInternal)
			: GET_FUNCTION_NAME_CHECKED(AHUICRSyncActor, ReadReceivedPayloadWithKeys);
	}
	else if (bSetSource)
	{
		FunctionName = GET_FUNCTION_NAME_CHECKED(AHUICRSyncActor, SetSyncFieldSourceInternal);
	}
	else if (UsesInitialPayload())
	{
		FunctionName = GET_FUNCTION_NAME_CHECKED(AHUICRSyncActor, SetInitialPayloadInternal);
	}
	UClass* PayloadOwner = Compiler.Blueprint->ParentClass->IsChildOf(AHUICRSyncHMDPawn::StaticClass())
		? AHUICRSyncHMDPawn::StaticClass() : AHUICRSyncActor::StaticClass();
	UK2Node_CallFunction* ActorCall = SpawnCall(PayloadOwner, FunctionName);
	auto* BoxCall = SpawnCall(UBlueprintInstancedStructLibrary::StaticClass(),
		bRead ? GET_FUNCTION_NAME_CHECKED(UBlueprintInstancedStructLibrary, GetInstancedStructValue)
		: GET_FUNCTION_NAME_CHECKED(UBlueprintInstancedStructLibrary, MakeInstancedStruct));
	UEdGraphPin* TypedValue = BoxCall->FindPinChecked(HUICRSyncNode::Value);
	TypedValue->PinType.PinCategory = Schema->PC_Struct;
	TypedValue->PinType.PinSubCategoryObject = Struct;

	if (bRead)
	{
		Compiler.MovePinLinksToIntermediate(*GetExecPin(), *ActorCall->GetExecPin());
		Connect(ActorCall->FindPin(Schema->PN_Then), BoxCall->GetExecPin());
		Connect(ActorCall->FindPin(TEXT("Payload")), BoxCall->FindPin(TEXT("InstancedStruct")));
		if (!UsesInitialPayload())
		{
			Compiler.MovePinLinksToIntermediate(*FindPinChecked(HUICRSyncNode::FieldsToApply), *ActorCall->FindPinChecked(HUICRSyncNode::FieldsToApply));
		}
		UEdGraphPin* Valid = BoxCall->FindPinChecked(TEXT("Valid"));
		Compiler.MovePinLinksToIntermediate(*FindPinChecked(HUICRSyncNode::NoValidPayload), *BoxCall->FindPinChecked(TEXT("NotValid")));
		auto* Break = Compiler.SpawnIntermediateNode<UK2Node_BreakStruct>(this, SourceGraph);
		Break->StructType = Struct;
		Break->bMadeAfterOverridePinRemoval = true;
		Break->AllocateDefaultPins();
		Connect(TypedValue, Break->FindPin(Struct->GetFName(), EGPD_Input));
		UK2Node_ExecutionSequence* Sequence = nullptr;
		int32 NextFieldBranch = 1; // Then 0 preserves the original Valid output.
		for (TFieldIterator<FProperty> It(Struct); It; ++It)
		{
			if (!HUICRSyncFields::IsSupportedField(**It))
			{
				continue;
			}
			MoveMember(**It, Break);
			UEdGraphPin* FieldExec = FindPin(FieldExecPinName(It->GetFName()), EGPD_Output);
			if (!FieldExec || FieldExec->LinkedTo.IsEmpty() || FieldExec->bOrphanedPin)
			{
				continue;
			}
			// Expand only connected field outputs. Every branch uses the mask from the same read.
			if (!Sequence)
			{
				Sequence = Compiler.SpawnIntermediateNode<UK2Node_ExecutionSequence>(this, SourceGraph);
				Sequence->AllocateDefaultPins();
				Connect(Valid, Sequence->GetExecPin());
			}
			if (NextFieldBranch >= 2)
			{
				Sequence->AddInputPin();
			}
			auto* Contains = Compiler.SpawnIntermediateNode<UK2Node_CallArrayFunction>(this, SourceGraph);
			Contains->SetFromFunction(UKismetArrayLibrary::StaticClass()->FindFunctionByName(
				GET_FUNCTION_NAME_CHECKED(UKismetArrayLibrary, Array_Contains)));
			Contains->AllocateDefaultPins();
			// A Blueprint field's authored label can lose spaces during cooking. Its reflected key survives.
			Connect(ActorCall->FindPinChecked(TEXT("FieldKeys")), Contains->GetTargetArrayPin());
			Schema->TrySetDefaultValue(*Contains->FindPinChecked(TEXT("ItemToFind")), It->GetName());

			auto* Branch = Compiler.SpawnIntermediateNode<UK2Node_IfThenElse>(this, SourceGraph);
			Branch->AllocateDefaultPins();
			Connect(Sequence->GetThenPinGivenIndex(NextFieldBranch++), Branch->GetExecPin());
			Connect(Contains->GetReturnValuePin(), Branch->GetConditionPin());
			Compiler.MovePinLinksToIntermediate(*FieldExec, *Branch->GetThenPin());
		}
		Compiler.MovePinLinksToIntermediate(*FindPinChecked(HUICRSyncNode::Valid),
			Sequence ? *Sequence->GetThenPinGivenIndex(0) : *Valid);
	}
	else
	{
		auto* Make = Compiler.SpawnIntermediateNode<UK2Node_MakeStruct>(this, SourceGraph);
		Make->StructType = Struct;
		Make->bMadeAfterOverridePinRemoval = true;
		Make->AllocateDefaultPins();
		Connect(Make->FindPin(Struct->GetFName(), EGPD_Output), TypedValue);
		Compiler.MovePinLinksToIntermediate(*GetExecPin(), *BoxCall->GetExecPin());
		Connect(BoxCall->FindPin(Schema->PN_Then), ActorCall->GetExecPin());
		Connect(BoxCall->GetReturnValuePin(), ActorCall->FindPin(TEXT("Payload")));
		Compiler.MovePinLinksToIntermediate(*FindPinChecked(Schema->PN_Then), *ActorCall->FindPinChecked(Schema->PN_Then));
		if (bSetSource)
		{
			ActorCall->FindPinChecked(HUICRSyncNode::Field)->DefaultValue = SelectedProperty->GetName();
			ActorCall->FindPinChecked(HUICRSyncNode::Source)->DefaultValue = FindPinChecked(HUICRSyncNode::Source)->DefaultValue;
			if (SelectedSource == EHUICRSyncFieldSource::UseSpecifiedValue)
			{
				MoveMember(*SelectedProperty, Make);
			}
		}
		else
		{
			for (TFieldIterator<FProperty> It(Struct); It; ++It)
			{
				if (HUICRSyncFields::IsSupportedField(**It))
				{
					MoveMember(**It, Make);
				}
			}
		}
	}
	BreakAllNodeLinks();
}

