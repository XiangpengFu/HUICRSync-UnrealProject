namespace HUICRSyncNode
{
	const FName Field(TEXT("Field"));
	const FName Mode(TEXT("Mode"));
	const FName Source(TEXT("Source"));
	const FName Value(TEXT("Value"));
	const FName Valid(TEXT("Valid"));
	const FName NoValidPayload(TEXT("NoValidPayload"));
	const FName FieldsToApply(TEXT("FieldsToApply"));
	const FString MemberPinPrefix(TEXT("Member."));

	FName AuthoredName(const FProperty& Property)
	{
		return FName(*Property.GetAuthoredName());
	}

	FProperty* FindSelectedProperty(UScriptStruct* Struct, FName Selection)
	{
		for (TFieldIterator<FProperty> It(Struct); It; ++It)
		{
			if (HUICRSyncFields::IsSupportedField(**It) && AuthoredName(**It) == Selection)
			{
				return *It;
			}
		}
		return nullptr;
	}
}

FName UK2Node_HUICRSyncPayload::MemberPinName(FName PropertyName)
{
	return FName(*(HUICRSyncNode::MemberPinPrefix + PropertyName.ToString()));
}

FName UK2Node_HUICRSyncPayload::FieldExecPinName(FName PropertyName)
{
	return FName(*(TEXT("Apply.") + PropertyName.ToString()));
}

bool UK2Node_HUICRSyncPayload::IsReadNode() const
{
	return IsA<UK2Node_ReadSyncPayload>() || IsA<UK2Node_ReadReceivedPayload>();
}

bool UK2Node_HUICRSyncPayload::UsesInitialPayload() const
{
	return bInitialMode || IsA<UK2Node_SetInitialPayload>();
}

void UK2Node_HUICRSyncPayload::AddModePin()
{
	const bool bRead = IsA<UK2Node_ReadSyncPayload>();
	UEnum* Enum = bRead ? StaticEnum<EHUICRSyncPayloadReadMode>() : StaticEnum<EHUICRSyncPayloadWriteMode>();
	FCreatePinParams Params;
	Params.Index = 1; // Immediately after the execution input, including on upgraded nodes.
	UEdGraphPin* ModePin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Byte, Enum, HUICRSyncNode::Mode, Params);
	ModePin->bNotConnectable = true;
	const TCHAR* DefaultMode = bRead ? TEXT("Received") : TEXT("Outgoing");
	GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(ModePin, bInitialMode ? TEXT("Initial") : DefaultMode);
}

void UK2Node_HUICRSyncPayload::AddMissingFieldExecPins()
{
	if (!IsA<UK2Node_ReadSyncPayload>() || UsesInitialPayload())
	{
		return;
	}
	// Work from the existing value pins so loading an older graph preserves its links and split pins,
	// even when its owning Blueprint's class defaults have not been loaded yet.
	for (int32 Index = Pins.Num() - 1; Index >= 0; --Index)
	{
		const UEdGraphPin* ValuePin = Pins[Index];
		if (!ValuePin || ValuePin->ParentPin || ValuePin->bOrphanedPin || ValuePin->Direction != EGPD_Output)
		{
			continue;
		}
		FString PropertyName = ValuePin->PinName.ToString();
		if (!PropertyName.RemoveFromStart(HUICRSyncNode::MemberPinPrefix))
		{
			continue;
		}
		const FName ExecName = FieldExecPinName(FName(*PropertyName));
		if (!FindPin(ExecName, EGPD_Output))
		{
			FCreatePinParams Params;
			Params.Index = Index;
			UEdGraphPin* Exec = CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, ExecName, Params);
			Exec->PinFriendlyName = FText::Format(LOCTEXT("ApplyField", "Apply {0}"), ValuePin->PinFriendlyName);
			Exec->PinToolTip = LOCTEXT("ApplyFieldTip", "Runs when this field is listed in Fields To Apply for this read.").ToString();
			Exec->SetSavePinIfOrphaned(false);
		}
	}
}

void UK2Node_HUICRSyncPayload::PostLoad()
{
	Super::PostLoad();
	AddMissingFieldExecPins();
}

void UK2Node_HUICRSyncPayload::ConvertDeprecatedNode(UEdGraph* Graph, bool bOnlySafeChanges)
{
	Super::ConvertDeprecatedNode(Graph, bOnlySafeChanges);
	const bool bOldRead = IsA<UK2Node_ReadReceivedPayload>();
	const bool bOldInitial = IsA<UK2Node_SetInitialPayload>();
	if (!bOldRead && !bOldInitial && !IsA<UK2Node_PrepareOutgoingPayload>())
	{
		return;
	}
	if (!Graph || Graph != GetGraph() || Pins.ContainsByPredicate([](UEdGraphPin* Pin) { return !Pin || Pin->bOrphanedPin; })
		|| !GetExecPin() || FindPin(HUICRSyncNode::Mode))
	{
		return; // Keep incomplete legacy nodes available for manual repair.
	}

	const UClass* ReplacementClass = bOldRead ? UK2Node_ReadSyncPayload::StaticClass() : UK2Node_WriteSyncPayload::StaticClass();
	auto* Replacement = NewObject<UK2Node_HUICRSyncPayload>(Graph, ReplacementClass, NAME_None, RF_Transactional);
	Replacement->bInitialMode = bOldInitial;
	Replacement->CachedPayloadStruct = CachedPayloadStruct;
	Replacement->NodeGuid = NodeGuid;
	Replacement->NodePosX = NodePosX;
	Replacement->NodePosY = NodePosY;
	Replacement->NodeComment = NodeComment;
	Replacement->bCommentBubblePinned = bCommentBubblePinned;
	Replacement->bCommentBubbleVisible = bCommentBubbleVisible;
	Replacement->AdvancedPinDisplay = AdvancedPinDisplay;
	Replacement->SetEnabledState(GetDesiredEnabledState(), HasUserSetTheEnabledState());

	// Keep the actual value pins (including split children, literal defaults and links).
	Replacement->Pins = MoveTemp(Pins);
	for (UEdGraphPin* Pin : Replacement->Pins)
	{
		Pin->SetOwningNode(Replacement);
	}
	if (UEdGraphPin* Mask = Replacement->FindPin(HUICRSyncNode::FieldsToApply))
	{
		Mask->SetSavePinIfOrphaned(false);
	}
	Replacement->AddModePin();
	Replacement->AddMissingFieldExecPins();
	Graph->AddNode(Replacement, false, false);
	FLinkerLoad::InvalidateExport(this);
	DestroyNode();
}

UScriptStruct* UK2Node_HUICRSyncPayload::ResolvePayloadStruct() const
{
	const UBlueprint* BP = FBlueprintEditorUtils::FindBlueprintForNode(this);
	if (!BP || (BP->bBeingCompiled && CachedPayloadStruct))
	{
		return CachedPayloadStruct;
	}
	const UClass* Class = BP->GeneratedClass ? BP->GeneratedClass.Get() : BP->ParentClass.Get();
	const UObject* Defaults = Class ? Class->GetDefaultObject() : nullptr;
	if (const auto* Pawn = Cast<AHUICRSyncHMDPawn>(Defaults))
	{
		return Pawn->SharedPayloadStruct;
	}
	const auto* Actor = Cast<AHUICRSyncActor>(Defaults);
	return Actor ? Actor->SharedPayloadStruct.Get() : nullptr;
}

void UK2Node_HUICRSyncPayload::GetFieldChoices(TArray<TSharedPtr<FName>>& Choices) const
{
	Choices.Reset();
	if (UScriptStruct* Struct = ResolvePayloadStruct())
	{
		for (TFieldIterator<FProperty> It(Struct); It; ++It)
		{
			if (HUICRSyncFields::IsSupportedField(**It))
			{
				Choices.Add(MakeShared<FName>(HUICRSyncNode::AuthoredName(**It)));
			}
		}
	}
}

void UK2Node_HUICRSyncPayload::AllocateDefaultPins()
{
	Super::AllocateDefaultPins();
	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();
	const bool bRead = IsReadNode();
	const bool bSetSource = IsA<UK2Node_SetSyncFieldSource>();
	CachedPayloadStruct = ResolvePayloadStruct();

	CreatePin(EGPD_Input, Schema->PC_Exec, Schema->PN_Execute);
	if (IsA<UK2Node_WriteSyncPayload>() || IsA<UK2Node_ReadSyncPayload>())
	{
		AddModePin();
	}
	if (bRead)
	{
		CreatePin(EGPD_Output, Schema->PC_Exec, HUICRSyncNode::Valid);
		CreatePin(EGPD_Output, Schema->PC_Exec, HUICRSyncNode::NoValidPayload)->PinFriendlyName = LOCTEXT("NoValidPayload", "No Valid Payload");
		if (!UsesInitialPayload())
		{
			FCreatePinParams Params;
			Params.ContainerType = EPinContainerType::Array;
			UEdGraphPin* Mask = CreatePin(EGPD_Output, Schema->PC_Name, HUICRSyncNode::FieldsToApply, Params);
			Mask->PinFriendlyName = LOCTEXT("FieldsToApply", "Fields To Apply");
			Mask->PinToolTip = TEXT("Shared field names this device should apply for this update.");
			if (IsA<UK2Node_ReadSyncPayload>())
			{
				Mask->SetSavePinIfOrphaned(false);
			}
		}
	}
	else
	{
		CreatePin(EGPD_Output, Schema->PC_Exec, Schema->PN_Then);
	}
	if (bSetSource)
	{
		TArray<TSharedPtr<FName>> Choices;
		GetFieldChoices(Choices);
		if (SelectedField.IsNone() && !Choices.IsEmpty())
		{
			SelectedField = *Choices[0];
		}
		UEdGraphPin* FieldPin = CreatePin(EGPD_Input, Schema->PC_Name, HUICRSyncNode::Field);
		FieldPin->bNotConnectable = true;
		Schema->SetPinAutogeneratedDefaultValue(FieldPin, SelectedField.ToString());
		UEnum* Enum = StaticEnum<EHUICRSyncFieldSource>();
		UEdGraphPin* SourcePin = CreatePin(EGPD_Input, Schema->PC_Byte, Enum, HUICRSyncNode::Source);
		SourcePin->bNotConnectable = true;
		Schema->SetPinAutogeneratedDefaultValue(SourcePin, Enum->GetNameStringByValue(static_cast<int64>(SelectedSource)));
	}
	if (!CachedPayloadStruct || (bSetSource && SelectedSource == EHUICRSyncFieldSource::FollowMyPayload))
	{
		return;
	}
	PreloadObject(CachedPayloadStruct);
	FStructOnScope Defaults(CachedPayloadStruct);
	for (TFieldIterator<FProperty> It(CachedPayloadStruct); It; ++It)
	{
		FProperty& Property = **It;
		FEdGraphPinType PinType;
		if (!HUICRSyncFields::IsSupportedField(Property) || !Schema->ConvertPropertyToPinType(&Property, PinType)
			|| (bSetSource && HUICRSyncNode::AuthoredName(Property) != SelectedField))
		{
			continue;
		}
		const FName PinName = bSetSource ? HUICRSyncNode::Value : MemberPinName(Property.GetFName());
		UEdGraphPin* Pin = CreatePin(bRead ? EGPD_Output : EGPD_Input, PinType, PinName);
		Pin->PinFriendlyName = bSetSource ? LOCTEXT("SpecifiedValue", "Value") : Property.GetDisplayNameText();
		if (!bRead)
		{
			FString DefaultText;
			if (!PinType.IsContainer() && FBlueprintEditorUtils::PropertyValueToString(&Property, Defaults.GetStructMemory(), DefaultText)
				&& Schema->IsPinDefaultValid(Pin, DefaultText, nullptr, FText::GetEmpty()).IsEmpty())
			{
				Schema->SetPinAutogeneratedDefaultValue(Pin, DefaultText);
			}
			else
			{
				Schema->SetPinAutogeneratedDefaultValueBasedOnType(Pin);
			}
		}
		if (bSetSource)
		{
			Pin->SetSavePinIfOrphaned(false);
		}
	}
	AddMissingFieldExecPins();
}

void UK2Node_HUICRSyncPayload::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);
	if (!Pin)
	{
		return;
	}
	if (Pin->PinName == HUICRSyncNode::Mode)
	{
		const UEnum* Enum = CastChecked<UEnum>(Pin->PinType.PinSubCategoryObject.Get());
		const int64 Value = Enum->GetValueByNameString(Pin->DefaultValue);
		if (Value == INDEX_NONE)
		{
			return;
		}
		const bool bNewInitialMode = Enum->GetNameStringByValue(Value) == TEXT("Initial");
		if (bInitialMode == bNewInitialMode)
		{
			return;
		}
		bInitialMode = bNewInitialMode;
	}
	else if (!IsA<UK2Node_SetSyncFieldSource>())
	{
		return;
	}
	else if (Pin->PinName == HUICRSyncNode::Field)
	{
		const FName NewField(*Pin->DefaultValue);
		if (SelectedField == NewField)
		{
			return;
		}
		SelectedField = NewField;
	}
	else if (Pin->PinName == HUICRSyncNode::Source)
	{
		const int64 Index = StaticEnum<EHUICRSyncFieldSource>()->GetValueByNameString(Pin->DefaultValue);
		if (Index == INDEX_NONE || SelectedSource == static_cast<EHUICRSyncFieldSource>(Index))
		{
			return;
		}
		SelectedSource = static_cast<EHUICRSyncFieldSource>(Index);
	}
	else
	{
		return;
	}
	ReconstructNode();
	GetGraph()->NotifyGraphChanged();
}

bool UK2Node_HUICRSyncPayload::IsCompatibleWithGraph(const UEdGraph* TargetGraph) const
{
	const UBlueprint* BP = TargetGraph ? FBlueprintEditorUtils::FindBlueprintForGraph(TargetGraph) : nullptr;
	return BP && BP->ParentClass && (BP->ParentClass->IsChildOf(AHUICRSyncActor::StaticClass()) ||
		BP->ParentClass->IsChildOf(AHUICRSyncHMDPawn::StaticClass()))
		&& Super::IsCompatibleWithGraph(TargetGraph);
}

bool UK2Node_HUICRSyncPayload::HasExternalDependencies(TArray<UStruct*>* OptionalOutput) const
{
	const bool bSuperHasDependencies = Super::HasExternalDependencies(OptionalOutput);
	if (CachedPayloadStruct && !CachedPayloadStruct->IsNative())
	{
		if (OptionalOutput)
		{
			OptionalOutput->AddUnique(CachedPayloadStruct);
		}
		return true;
	}
	return bSuperHasDependencies;
}

void UK2Node_HUICRSyncPayload::GetMenuActions(FBlueprintActionDatabaseRegistrar& Registrar) const
{
	// The single-mode classes remain loadable for existing graphs.
	if ((IsA<UK2Node_WriteSyncPayload>() || IsA<UK2Node_ReadSyncPayload>() || IsA<UK2Node_SetSyncFieldSource>())
		&& Registrar.IsOpenForRegistration(GetClass()))
	{
		Registrar.AddBlueprintAction(GetClass(), UBlueprintNodeSpawner::Create(GetClass()));
	}
}

FText UK2Node_HUICRSyncPayload::GetNodeTitle(ENodeTitleType::Type TitleType) const
{
	if (IsA<UK2Node_WriteSyncPayload>())
	{
		return LOCTEXT("WriteSyncPayload", "Write Sync Payload");
	}
	if (IsA<UK2Node_ReadSyncPayload>())
	{
		return LOCTEXT("ReadSyncPayload", "Read Sync Payload");
	}
	if (IsA<UK2Node_SetInitialPayload>())
	{
		return LOCTEXT("SetInitial", "Set Initial Payload");
	}
	if (IsA<UK2Node_PrepareOutgoingPayload>())
	{
		return LOCTEXT("Prepare", "Prepare Outgoing Payload");
	}
	return IsA<UK2Node_ReadReceivedPayload>() ? LOCTEXT("Read", "Read Received Payload") : LOCTEXT("SetSource", "Set Sync Field Source");
}

FText UK2Node_HUICRSyncPayload::GetPinDisplayName(const UEdGraphPin* Pin) const
{
	if (Pin && Pin->PinName == HUICRSyncNode::Mode)
	{
		return IsReadNode() ? LOCTEXT("ReadFromPin", "Read From") : LOCTEXT("WriteToPin", "Write To");
	}
	return Super::GetPinDisplayName(Pin);
}

FText UK2Node_HUICRSyncPayload::GetTooltipText() const
{
	if (IsA<UK2Node_WriteSyncPayload>())
	{
		return LOCTEXT("WriteSyncPayloadTip", "Choose Initial Values to set the starting values for the counterpart. In On Prepare Sync Fields, choose Current Local Values to supply the fields listed for this device.");
	}
	if (IsA<UK2Node_ReadSyncPayload>())
	{
		return LOCTEXT("ReadSyncPayloadTip", "Choose Initial Values to read this actor's spawn values. Choose Received Values to read the latest values confirmed by the PC. After Valid, each connected Apply output runs if its field is listed in Fields To Apply.");
	}
	if (IsA<UK2Node_SetInitialPayload>())
	{
		return LOCTEXT("SetInitialTip", "Set the starting values sent when the PC creates this actor's mirrors. Call during actor setup, before its first scene capture. Later gameplay changes use Set Sync Field Source.");
	}
	if (IsA<UK2Node_PrepareOutgoingPayload>())
	{
		return LOCTEXT("PrepareTip", "Prepare this actor's current local values. Only fields following this device can be sent.");
	}
	return IsA<UK2Node_ReadReceivedPayload>()
		? LOCTEXT("ReadTip", "Read the shared state confirmed by the PC. Fields To Apply lists remote changes to apply locally.")
		: LOCTEXT("SetTip", "Ask the PC to use a fixed value or follow this device's prepared values for the selected field. Call from a local interaction.");
}

