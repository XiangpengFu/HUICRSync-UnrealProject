namespace HUICRSyncNode
{
	const FName Field(TEXT("Field"));
	const FName Source(TEXT("Source"));
	const FName Value(TEXT("Value"));
	const FName Valid(TEXT("Valid"));
	const FName NoValidPayload(TEXT("NoValidPayload"));
	const FName FieldsToApply(TEXT("FieldsToApply"));

	FName AuthoredName(const FProperty& Property)
	{
		return FName(*Property.GetAuthoredName());
	}

	FProperty* FindSelectedProperty(UScriptStruct* Struct, FName Selection)
	{
		for (TFieldIterator<FProperty> It(Struct); It; ++It)
		{
			if (HUICRSyncFields::IsSupportedField(**It) && AuthoredName(**It) == Selection)
			{
				return *It;
			}
		}
		return nullptr;
	}
}

FName UK2Node_HUICRSyncPayload::MemberPinName(FName PropertyName)
{
	return FName(*(TEXT("Member.") + PropertyName.ToString()));
}

UScriptStruct* UK2Node_HUICRSyncPayload::ResolvePayloadStruct() const
{
	const UBlueprint* BP = FBlueprintEditorUtils::FindBlueprintForNode(this);
	if (!BP || (BP->bBeingCompiled && CachedPayloadStruct))
	{
		return CachedPayloadStruct;
	}
	const UClass* Class = BP->GeneratedClass ? BP->GeneratedClass.Get() : BP->ParentClass.Get();
	const AHUICRSyncActor* Defaults = Class ? Cast<AHUICRSyncActor>(Class->GetDefaultObject()) : nullptr;
	return Defaults ? Defaults->SharedPayloadStruct.Get() : nullptr;
}

void UK2Node_HUICRSyncPayload::GetFieldChoices(TArray<TSharedPtr<FName>>& Choices) const
{
	Choices.Reset();
	if (UScriptStruct* Struct = ResolvePayloadStruct())
	{
		for (TFieldIterator<FProperty> It(Struct); It; ++It)
		{
			if (HUICRSyncFields::IsSupportedField(**It))
			{
				Choices.Add(MakeShared<FName>(HUICRSyncNode::AuthoredName(**It)));
			}
		}
	}
}

void UK2Node_HUICRSyncPayload::AllocateDefaultPins()
{
	Super::AllocateDefaultPins();
	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();
	const bool bRead = IsA<UK2Node_ReadReceivedPayload>();
	const bool bSetSource = IsA<UK2Node_SetSyncFieldSource>();
	CachedPayloadStruct = ResolvePayloadStruct();

	CreatePin(EGPD_Input, Schema->PC_Exec, Schema->PN_Execute);
	if (bRead)
	{
		CreatePin(EGPD_Output, Schema->PC_Exec, HUICRSyncNode::Valid);
		CreatePin(EGPD_Output, Schema->PC_Exec, HUICRSyncNode::NoValidPayload)->PinFriendlyName = LOCTEXT("NoValidPayload", "No Valid Payload");
		FCreatePinParams Params;
		Params.ContainerType = EPinContainerType::Array;
		UEdGraphPin* Mask = CreatePin(EGPD_Output, Schema->PC_Name, HUICRSyncNode::FieldsToApply, Params);
		Mask->PinFriendlyName = LOCTEXT("FieldsToApply", "Fields To Apply");
		Mask->PinToolTip = TEXT("Shared field names this device should apply for this update.");
	}
	else
	{
		CreatePin(EGPD_Output, Schema->PC_Exec, Schema->PN_Then);
	}
	if (bSetSource)
	{
		TArray<TSharedPtr<FName>> Choices;
		GetFieldChoices(Choices);
		if (SelectedField.IsNone() && !Choices.IsEmpty())
		{
			SelectedField = *Choices[0];
		}
		UEdGraphPin* FieldPin = CreatePin(EGPD_Input, Schema->PC_Name, HUICRSyncNode::Field);
		FieldPin->bNotConnectable = true;
		Schema->SetPinAutogeneratedDefaultValue(FieldPin, SelectedField.ToString());
		UEnum* Enum = StaticEnum<EHUICRSyncFieldSource>();
		UEdGraphPin* SourcePin = CreatePin(EGPD_Input, Schema->PC_Byte, Enum, HUICRSyncNode::Source);
		SourcePin->bNotConnectable = true;
		Schema->SetPinAutogeneratedDefaultValue(SourcePin, Enum->GetNameStringByValue(static_cast<int64>(SelectedSource)));
	}
	if (!CachedPayloadStruct || (bSetSource && SelectedSource == EHUICRSyncFieldSource::FollowMyPayload))
	{
		return;
	}
	PreloadObject(CachedPayloadStruct);
	FStructOnScope Defaults(CachedPayloadStruct);
	for (TFieldIterator<FProperty> It(CachedPayloadStruct); It; ++It)
	{
		FProperty& Property = **It;
		FEdGraphPinType PinType;
		if (!HUICRSyncFields::IsSupportedField(Property) || !Schema->ConvertPropertyToPinType(&Property, PinType)
			|| (bSetSource && HUICRSyncNode::AuthoredName(Property) != SelectedField))
		{
			continue;
		}
		const FName PinName = bSetSource ? HUICRSyncNode::Value : MemberPinName(Property.GetFName());
		UEdGraphPin* Pin = CreatePin(bRead ? EGPD_Output : EGPD_Input, PinType, PinName);
		Pin->PinFriendlyName = bSetSource ? LOCTEXT("SpecifiedValue", "Value") : Property.GetDisplayNameText();
		if (!bRead)
		{
			FString DefaultText;
			if (!PinType.IsContainer() && FBlueprintEditorUtils::PropertyValueToString(&Property, Defaults.GetStructMemory(), DefaultText)
				&& Schema->IsPinDefaultValid(Pin, DefaultText, nullptr, FText::GetEmpty()).IsEmpty())
			{
				Schema->SetPinAutogeneratedDefaultValue(Pin, DefaultText);
			}
			else
			{
				Schema->SetPinAutogeneratedDefaultValueBasedOnType(Pin);
			}
		}
		if (bSetSource)
		{
			Pin->SetSavePinIfOrphaned(false);
		}
	}
}

void UK2Node_HUICRSyncPayload::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);
	if (!IsA<UK2Node_SetSyncFieldSource>() || !Pin)
	{
		return;
	}
	if (Pin->PinName == HUICRSyncNode::Field)
	{
		const FName NewField(*Pin->DefaultValue);
		if (SelectedField == NewField)
		{
			return;
		}
		SelectedField = NewField;
	}
	else if (Pin->PinName == HUICRSyncNode::Source)
	{
		const int64 Index = StaticEnum<EHUICRSyncFieldSource>()->GetValueByNameString(Pin->DefaultValue);
		if (Index == INDEX_NONE || SelectedSource == static_cast<EHUICRSyncFieldSource>(Index))
		{
			return;
		}
		SelectedSource = static_cast<EHUICRSyncFieldSource>(Index);
	}
	else
	{
		return;
	}
	ReconstructNode();
	GetGraph()->NotifyGraphChanged();
}

bool UK2Node_HUICRSyncPayload::IsCompatibleWithGraph(const UEdGraph* TargetGraph) const
{
	const UBlueprint* BP = TargetGraph ? FBlueprintEditorUtils::FindBlueprintForGraph(TargetGraph) : nullptr;
	return BP && BP->ParentClass && BP->ParentClass->IsChildOf(AHUICRSyncActor::StaticClass())
		&& Super::IsCompatibleWithGraph(TargetGraph);
}

bool UK2Node_HUICRSyncPayload::HasExternalDependencies(TArray<UStruct*>* OptionalOutput) const
{
	const bool bSuperHasDependencies = Super::HasExternalDependencies(OptionalOutput);
	if (CachedPayloadStruct && !CachedPayloadStruct->IsNative())
	{
		if (OptionalOutput)
		{
			OptionalOutput->AddUnique(CachedPayloadStruct);
		}
		return true;
	}
	return bSuperHasDependencies;
}

void UK2Node_HUICRSyncPayload::GetMenuActions(FBlueprintActionDatabaseRegistrar& Registrar) const
{
	if (!GetClass()->HasAnyClassFlags(CLASS_Abstract) && Registrar.IsOpenForRegistration(GetClass()))
	{
		Registrar.AddBlueprintAction(GetClass(), UBlueprintNodeSpawner::Create(GetClass()));
	}
}

FText UK2Node_HUICRSyncPayload::GetNodeTitle(ENodeTitleType::Type TitleType) const
{
	if (IsA<UK2Node_SetInitialPayload>())
	{
		return LOCTEXT("SetInitial", "Set Initial Payload");
	}
	if (IsA<UK2Node_PrepareOutgoingPayload>())
	{
		return LOCTEXT("Prepare", "Prepare Outgoing Payload");
	}
	return IsA<UK2Node_ReadReceivedPayload>() ? LOCTEXT("Read", "Read Received Payload") : LOCTEXT("SetSource", "Set Sync Field Source");
}

FText UK2Node_HUICRSyncPayload::GetTooltipText() const
{
	if (IsA<UK2Node_SetInitialPayload>())
	{
		return LOCTEXT("SetInitialTip", "Set the starting values sent when the PC creates this actor's mirrors. Call during actor setup, before its first scene capture. Later gameplay changes use Set Sync Field Source.");
	}
	if (IsA<UK2Node_PrepareOutgoingPayload>())
	{
		return LOCTEXT("PrepareTip", "Prepare this actor's current local values. Only fields following this device can be sent.");
	}
	return IsA<UK2Node_ReadReceivedPayload>()
		? LOCTEXT("ReadTip", "Read the shared state confirmed by the PC. Fields To Apply lists remote changes to apply locally.")
		: LOCTEXT("SetTip", "Ask the PC to use a fixed value or follow this device's prepared values for the selected field. Call from a local interaction.");
}

FText UK2Node_HUICRSyncPayload::GetMenuCategory() const
{
	return LOCTEXT("Category", "HUICR Sync|Payload");
}

void UK2Node_HUICRSyncPayload::ExpandNode(FKismetCompilerContext& Compiler, UEdGraph* SourceGraph)
{
	Super::ExpandNode(Compiler, SourceGraph);
	UScriptStruct* Struct = ResolvePayloadStruct();
	if (!Struct)
	{
		Compiler.MessageLog.Error(TEXT("@@ requires a Shared Payload Struct in the Sync Actor's Class Defaults."), this);
		BreakAllNodeLinks();
		return;
	}
	if (IsA<UK2Node_SetInitialPayload>() && !HUICRSyncFields::CanUseLegacyBytes(Struct))
	{
		Compiler.MessageLog.Error(TEXT("@@ requires a value-only Shared Payload Struct for spawn data. Use a shared ID for an object reference and remove delegates from this struct."), this);
		BreakAllNodeLinks();
		return;
	}
	const UEdGraphSchema_K2* Schema = Compiler.GetSchema();
	const bool bRead = IsA<UK2Node_ReadReceivedPayload>();
	const bool bSetSource = IsA<UK2Node_SetSyncFieldSource>();
	FProperty* SelectedProperty = bSetSource ? HUICRSyncNode::FindSelectedProperty(Struct, SelectedField) : nullptr;
	if (bSetSource && !SelectedProperty)
	{
		Compiler.MessageLog.Error(TEXT("@@ selects a field missing from the Shared Payload Struct. Pick a field from the dropdown."), this);
		BreakAllNodeLinks();
		return;
	}

	auto SpawnCall = [&](UClass* Owner, FName FunctionName)
	{
		auto* Call = Compiler.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
		Call->SetFromFunction(Owner->FindFunctionByName(FunctionName));
		Call->AllocateDefaultPins();
		return Call;
	};
	auto Connect = [&](UEdGraphPin* First, UEdGraphPin* Second)
	{
		if (!First || !Second || !Schema->TryCreateConnection(First, Second))
		{
			Compiler.MessageLog.Error(TEXT("@@ could not connect its internal payload pins. Refresh the node and check the shared structure."), this);
		}
	};
	auto MoveMember = [&](const FProperty& Property, UK2Node* StructNode)
	{
		UEdGraphPin* Pin = FindPin(bSetSource ? HUICRSyncNode::Value : MemberPinName(Property.GetFName()));
		UEdGraphPin* Intermediate = StructNode->FindPin(Property.GetFName(), bRead ? EGPD_Output : EGPD_Input);
		if (!Pin || !Intermediate || Pin->PinType != Intermediate->PinType)
		{
			Compiler.MessageLog.Error(*FString::Printf(TEXT("@@ cannot expose '%s'. Check the field type and refresh the node."), *Property.GetAuthoredName()), this);
			return;
		}
		Compiler.MovePinLinksToIntermediate(*Pin, *Intermediate);
	};
	FName FunctionName = GET_FUNCTION_NAME_CHECKED(AHUICRSyncActor, PrepareOutgoingPayloadInternal);
	if (bRead)
	{
		FunctionName = GET_FUNCTION_NAME_CHECKED(AHUICRSyncActor, ReadReceivedPayloadInternal);
	}
	else if (bSetSource)
	{
		FunctionName = GET_FUNCTION_NAME_CHECKED(AHUICRSyncActor, SetSyncFieldSourceInternal);
	}
	else if (IsA<UK2Node_SetInitialPayload>())
	{
		FunctionName = GET_FUNCTION_NAME_CHECKED(AHUICRSyncActor, SetInitialPayloadInternal);
	}
	UK2Node_CallFunction* ActorCall = SpawnCall(AHUICRSyncActor::StaticClass(), FunctionName);
	auto* BoxCall = SpawnCall(UBlueprintInstancedStructLibrary::StaticClass(),
		bRead ? GET_FUNCTION_NAME_CHECKED(UBlueprintInstancedStructLibrary, GetInstancedStructValue)
		: GET_FUNCTION_NAME_CHECKED(UBlueprintInstancedStructLibrary, MakeInstancedStruct));
	UEdGraphPin* TypedValue = BoxCall->FindPinChecked(HUICRSyncNode::Value);
	TypedValue->PinType.PinCategory = Schema->PC_Struct;
	TypedValue->PinType.PinSubCategoryObject = Struct;

	if (bRead)
	{
		Compiler.MovePinLinksToIntermediate(*GetExecPin(), *ActorCall->GetExecPin());
		Connect(ActorCall->FindPin(Schema->PN_Then), BoxCall->GetExecPin());
		Connect(ActorCall->FindPin(TEXT("Payload")), BoxCall->FindPin(TEXT("InstancedStruct")));
		Compiler.MovePinLinksToIntermediate(*FindPinChecked(HUICRSyncNode::FieldsToApply), *ActorCall->FindPinChecked(HUICRSyncNode::FieldsToApply));
		Compiler.MovePinLinksToIntermediate(*FindPinChecked(HUICRSyncNode::Valid), *BoxCall->FindPinChecked(TEXT("Valid")));
		Compiler.MovePinLinksToIntermediate(*FindPinChecked(HUICRSyncNode::NoValidPayload), *BoxCall->FindPinChecked(TEXT("NotValid")));
		auto* Break = Compiler.SpawnIntermediateNode<UK2Node_BreakStruct>(this, SourceGraph);
		Break->StructType = Struct;
		Break->bMadeAfterOverridePinRemoval = true;
		Break->AllocateDefaultPins();
		Connect(TypedValue, Break->FindPin(Struct->GetFName(), EGPD_Input));
		for (TFieldIterator<FProperty> It(Struct); It; ++It)
		{
			if (HUICRSyncFields::IsSupportedField(**It))
			{
				MoveMember(**It, Break);
			}
		}
	}
	else
	{
		auto* Make = Compiler.SpawnIntermediateNode<UK2Node_MakeStruct>(this, SourceGraph);
		Make->StructType = Struct;
		Make->bMadeAfterOverridePinRemoval = true;
		Make->AllocateDefaultPins();
		Connect(Make->FindPin(Struct->GetFName(), EGPD_Output), TypedValue);
		Compiler.MovePinLinksToIntermediate(*GetExecPin(), *BoxCall->GetExecPin());
		Connect(BoxCall->FindPin(Schema->PN_Then), ActorCall->GetExecPin());
		Connect(BoxCall->GetReturnValuePin(), ActorCall->FindPin(TEXT("Payload")));
		Compiler.MovePinLinksToIntermediate(*FindPinChecked(Schema->PN_Then), *ActorCall->FindPinChecked(Schema->PN_Then));
		if (bSetSource)
		{
			ActorCall->FindPinChecked(HUICRSyncNode::Field)->DefaultValue = SelectedProperty->GetName();
			ActorCall->FindPinChecked(HUICRSyncNode::Source)->DefaultValue = FindPinChecked(HUICRSyncNode::Source)->DefaultValue;
			if (SelectedSource == EHUICRSyncFieldSource::UseSpecifiedValue)
			{
				MoveMember(*SelectedProperty, Make);
			}
		}
		else
		{
			for (TFieldIterator<FProperty> It(Struct); It; ++It)
			{
				if (HUICRSyncFields::IsSupportedField(**It))
				{
					MoveMember(**It, Make);
				}
			}
		}
	}
	BreakAllNodeLinks();
}

